def meta_type_id(meta_type):
    """
    Meta types as plain ints. pyds returns NvDsMetaType enums from some calls and
    ints from others, and an enum never equals an int, so compare the int values.
    """
    return int(meta_type)


def analytics_meta_types(level):
    """
    Meta type ids that nvdsanalytics may use for its OBJ / FRAME results.
    DeepStream <= 7.x registers them by name ("NVIDIA.DSANALYTICS<level>.USER_META");
    DeepStream 8.0 uses built-in enum values (NVDS_<level>_META_NVDSANALYTICS).
    Accept both so the app runs on either SDK.
    """
    ids = {meta_type_id(pyds.nvds_get_user_meta_type(f"NVIDIA.DSANALYTICS{level}.USER_META"))}
    builtin = getattr(pyds.NvDsMetaType, f"NVDS_{level}_META_NVDSANALYTICS", None)
    if builtin is not None:
        ids.add(meta_type_id(builtin))
    return ids


def user_meta_types(l_user):
    """List the meta type ids in a user-meta list (for the one-time debug log)."""
    types = []
    while l_user is not None:
        try:
            types.append(meta_type_id(pyds.NvDsUserMeta.cast(l_user.data).base_meta.meta_type))
            l_user = l_user.next
        except StopIteration:
            break
    return types


class VehicleCounter:
    """Reads DeepStream metadata on every batch and turns line crossings into DB events."""

    def __init__(self, writer):
        self.writer = writer
        self.colors = OrderedDict()   # tracker id -> (color, prob); latest classifier result
        self.counted = set()          # (source, tracker id, line) already counted
        self.totals = {"in": 0, "out": 0}
        self.frames = 0
        self.t0 = time.monotonic()
        # nvdsanalytics user-meta type ids, looked up on the first buffer (as NVIDIA's samples do)
        self.analytics_obj_type = None
        self.analytics_frame_type = None
        self.meta_types_logged = False
        # health check for the FPS log: objects carrying nvdsanalytics meta, and
        # nvdsanalytics' own cumulative line-crossing counts
        self.analytics_objs = 0
        self.lc_cum = {}

    # -- helpers -------------------------------------------------------------
    def _remember_color(self, obj_meta):
        """Pull the colour label from the SGIE classifier meta (if present)."""
        l_cls = obj_meta.classifier_meta_list
        while l_cls is not None:
            try:
                cls_meta = pyds.NvDsClassifierMeta.cast(l_cls.data)
            except StopIteration:
                break
            if cls_meta.unique_component_id == SGIE_ID:
                l_lbl = cls_meta.label_info_list
                while l_lbl is not None:
                    try:
                        lbl = pyds.NvDsLabelInfo.cast(l_lbl.data)
                    except StopIteration:
                        break
                    if lbl.result_label:
                        self.colors[obj_meta.object_id] = (lbl.result_label, float(lbl.result_prob))
                        self.colors.move_to_end(obj_meta.object_id)
                    try:
                        l_lbl = l_lbl.next
                    except StopIteration:
                        break
            try:
                l_cls = l_cls.next
            except StopIteration:
                break
        while len(self.colors) > 5000:          # keep memory bounded
            self.colors.popitem(last=False)
        return self.colors.get(obj_meta.object_id, ("unknown", None))

    def _crossed_lines(self, obj_meta):
        """Return the line names (e.g. ['in']) this object crossed in this frame."""
        crossed = []
        l_user = obj_meta.obj_user_meta_list
        while l_user is not None:
            try:
                user_meta = pyds.NvDsUserMeta.cast(l_user.data)
            except StopIteration:
                break
            if meta_type_id(user_meta.base_meta.meta_type) in self.analytics_obj_type:
                info = pyds.NvDsAnalyticsObjInfo.cast(user_meta.user_meta_data)
                self.analytics_objs += 1
                crossed.extend(info.lcStatus)
            try:
                l_user = l_user.next
            except StopIteration:
                break
        return crossed

    def _read_frame_analytics(self, frame_meta):
        """Remember nvdsanalytics' own cumulative line-crossing counts (for the FPS log)."""
        l_user = frame_meta.frame_user_meta_list
        while l_user is not None:
            try:
                user_meta = pyds.NvDsUserMeta.cast(l_user.data)
            except StopIteration:
                break
            if meta_type_id(user_meta.base_meta.meta_type) in self.analytics_frame_type:
                info = pyds.NvDsAnalyticsFrameMeta.cast(user_meta.user_meta_data)
                self.lc_cum = dict(info.objLCCumCnt)
            try:
                l_user = l_user.next
            except StopIteration:
                break

    def _draw_counters(self, batch_meta, frame_meta):
        display_meta = pyds.nvds_acquire_display_meta_from_pool(batch_meta)
        display_meta.num_labels = 1
        txt = display_meta.text_params[0]
        total = self.totals["in"] + self.totals["out"]
        txt.display_text = f"Total: {total}   In: {self.totals['in']}   Out: {self.totals['out']}"
        txt.x_offset, txt.y_offset = 12, 12
        txt.font_params.font_name = "Serif"
        txt.font_params.font_size = 16
        txt.font_params.font_color.set(1.0, 1.0, 1.0, 1.0)
        txt.set_bg_clr = 1
        txt.text_bg_clr.set(0.0, 0.0, 0.0, 0.6)
        pyds.nvds_add_display_meta_to_frame(frame_meta, display_meta)

    # -- the probe -----------------------------------------------------------
    def probe(self, pad, info, _user_data):
        gst_buffer = info.get_buffer()
        if not gst_buffer:
            return Gst.PadProbeReturn.OK
        try:
            self._process_batch(gst_buffer)
        except Exception:  # never let a Python error kill the video pipeline
            log.exception("Probe error")
        return Gst.PadProbeReturn.OK

    def _process_batch(self, gst_buffer):
        if self.analytics_obj_type is None:
            self.analytics_obj_type = analytics_meta_types("OBJ")
            self.analytics_frame_type = analytics_meta_types("FRAME")

        batch_meta = pyds.gst_buffer_get_nvds_batch_meta(hash(gst_buffer))
        l_frame = batch_meta.frame_meta_list
        while l_frame is not None:
            try:
                frame_meta = pyds.NvDsFrameMeta.cast(l_frame.data)
            except StopIteration:
                break

            if not self.meta_types_logged and frame_meta.obj_meta_list is not None:
                first_obj = pyds.NvDsObjectMeta.cast(frame_meta.obj_meta_list.data)
                log.info("Meta types: analytics obj=%s frame=%s | seen on object=%s frame=%s",
                         self.analytics_obj_type, self.analytics_frame_type,
                         user_meta_types(first_obj.obj_user_meta_list),
                         user_meta_types(frame_meta.frame_user_meta_list))
                self.meta_types_logged = True

            l_obj = frame_meta.obj_meta_list
            while l_obj is not None:
                try:
                    obj_meta = pyds.NvDsObjectMeta.cast(l_obj.data)
                except StopIteration:
                    break

                if obj_meta.unique_component_id == PGIE_ID:
                    color, prob = self._remember_color(obj_meta)
                    # label drawn by nvdsosd above each box: "<id> <colour>"
                    obj_meta.text_params.display_text = f"#{obj_meta.object_id} {color}"

                    for line in self._crossed_lines(obj_meta):
                        key = (frame_meta.source_id, obj_meta.object_id, line)
                        if key in self.counted:  # safety net: one count per ID per line
                            continue
                        self.counted.add(key)
                        direction = "in" if line.lower().endswith("in") else "out"
                        self.totals[direction] += 1
                        r = obj_meta.rect_params
                        event = VehicleEvent(
                            vehicle_id=int(obj_meta.object_id),
                            vehicle_class=obj_meta.obj_label or "car",
                            color=color,
                            color_confidence=prob,
                            direction=direction,
                            line_name=line,
                            source_id=int(frame_meta.source_id),
                            frame_number=int(frame_meta.frame_num),
                            bbox_left=float(r.left), bbox_top=float(r.top),
                            bbox_width=float(r.width), bbox_height=float(r.height),
                            event_time=datetime.now(timezone.utc),
                        )
                        self.writer.submit(event)  # non-blocking
                        log.info("COUNT  id=%-5d %-8s dir=%-3s total=%d",
                                 event.vehicle_id, color, direction,
                                 self.totals["in"] + self.totals["out"])
                try:
                    l_obj = l_obj.next
                except StopIteration:
                    break

            self._read_frame_analytics(frame_meta)
            self._draw_counters(batch_meta, frame_meta)
            self.frames += 1
            if self.frames % 150 == 0:
                fps = self.frames / (time.monotonic() - self.t0)
                log.info("FPS %.1f | in=%d out=%d | db inserted=%d queued=%d | "
                         "analytics objs=%d lc_cum=%s",
                         fps, self.totals["in"], self.totals["out"],
                         self.writer.inserted, self.writer.queue.qsize(),
                         self.analytics_objs, self.lc_cum)
            if len(self.counted) > 20000:
                self.counted.clear()

            try:
                l_frame = l_frame.next
            except StopIteration:
                break


