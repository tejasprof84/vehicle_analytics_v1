def make(factory, name, **props):
    elem = Gst.ElementFactory.make(factory, name)
    if not elem:
        sys.exit(f"Unable to create element '{factory}'. Is DeepStream installed correctly?")
    for key, value in props.items():
        elem.set_property(key.replace("_", "-"), value)
    return elem


def set_if_exists(elem, prop, value):
    """Set a property only if this DeepStream version has it (keeps the app portable)."""
    if elem.find_property(prop) is None:
        log.debug("%s has no property '%s' - skipped", elem.get_name(), prop)
        return
    try:
        elem.set_property(prop, value)
    except TypeError:
        Gst.util_set_object_arg(elem, prop, str(value))


def configure_tracker(tracker, path):
    cfg = configparser.ConfigParser()
    cfg.read(path)
    for key, value in cfg["tracker"].items():
        if key in ("tracker-width", "tracker-height", "gpu-id", "display-tracking-id"):
            tracker.set_property(key, int(value))
        elif key in ("ll-lib-file", "ll-config-file"):
            tracker.set_property(key, value)


def on_source_pad(_src, pad, mux_sinkpad):
    caps = pad.get_current_caps() or pad.query_caps()
    struct = caps.get_structure(0)
    if not struct.get_name().startswith("video"):
        return
    if not caps.get_features(0).contains("memory:NVMM"):
        log.error("Decoder did not output NVMM (GPU) memory")
        return
    if pad.link(mux_sinkpad) != Gst.PadLinkReturn.OK:
        log.error("Failed to link source to nvstreammux")
    else:
        log.info("RTSP source linked -> nvstreammux")


def start_rtsp_server(codec="H264"):
    """Serve the encoded output on rtsp://<host>:8555/ds (MediaMTX pulls from here)."""
    server = GstRtspServer.RTSPServer.new()
    server.props.service = str(RTSP_OUT_PORT)
    server.attach(None)
    factory = GstRtspServer.RTSPMediaFactory.new()
    factory.set_launch(
        f'( udpsrc name=pay0 port={UDP_PORT} buffer-size=524288 '
        f'caps="application/x-rtp, media=video, clock-rate=90000, '
        f'encoding-name=(string){codec}, payload=96" )')
    factory.set_shared(True)
    server.get_mount_points().add_factory(RTSP_OUT_MOUNT, factory)
    log.info("Annotated stream served at rtsp://0.0.0.0:%d%s", RTSP_OUT_PORT, RTSP_OUT_MOUNT)
    return server


def build_pipeline(args, counter):
    pipeline = Gst.Pipeline.new("vehicle-analytics")

    # 1) Source: RTSP from MediaMTX, decoded on the GPU
    source = make("nvurisrcbin", "rtsp-source", uri=args.uri)
    set_if_exists(source, "rtsp-reconnect-interval", 5)   # reconnect if stream drops
    set_if_exists(source, "latency", 200)                 # jitter buffer (ms)
    set_if_exists(source, "select-rtp-protocol", 4)       # 4 = TCP only (reliable)

    # 2) Batch frames
    mux = make("nvstreammux", "stream-muxer", batch_size=1, width=MUX_W, height=MUX_H,
               live_source=1, batched_push_timeout=40000)

    # 3) Primary detector, 4) tracker, 5) secondary colour classifier
    pgie = make("nvinfer", "primary-vehicle-detector",
                config_file_path=os.path.join(CFG, "pgie_trafficcamnet.txt"))
    tracker = make("nvtracker", "tracker")
    configure_tracker(tracker, os.path.join(CFG, "tracker_config.txt"))
    sgie = None
    if not args.skip_color:
        sgie = make("nvinfer", "secondary-color-classifier",
                    config_file_path=os.path.join(CFG, "sgie_color.txt"))

    # 6) Line crossing
    analytics = make("nvdsanalytics", "line-crossing",
                     config_file=write_analytics_config(
                         args.line, os.path.join(CFG, "nvdsanalytics.txt")))

    # 7) Drawing
    conv_osd = make("nvvideoconvert", "convert-for-osd")
    osd = make("nvdsosd", "on-screen-display")

    elements = [source, mux, pgie, tracker] + ([sgie] if sgie else []) + [analytics, conv_osd, osd]

    # 8) Output
    if args.sink == "rtsp":
        conv_enc = make("nvvideoconvert", "convert-for-encoder")
        if args.encoder == "nvenc":
            caps = make("capsfilter", "enc-caps",
                        caps=Gst.Caps.from_string("video/x-raw(memory:NVMM), format=I420"))
            encoder = make("nvv4l2h264enc", "h264-encoder", bitrate=4_000_000)
            set_if_exists(encoder, "insert-sps-pps", 1)   # let late viewers join
            set_if_exists(encoder, "iframeinterval", 30)
        else:  # CPU fallback for GPUs without NVENC (A100/H100)
            caps = make("capsfilter", "enc-caps",
                        caps=Gst.Caps.from_string("video/x-raw, format=I420"))
            encoder = make("x264enc", "h264-encoder", bitrate=4000)
            Gst.util_set_object_arg(encoder, "tune", "zerolatency")
            Gst.util_set_object_arg(encoder, "speed-preset", "ultrafast")
            encoder.set_property("key-int-max", 30)
        parser = make("h264parse", "h264-parser")
        payloader = make("rtph264pay", "rtp-payloader")
        sink = make("udpsink", "udp-sink", host="127.0.0.1", port=UDP_PORT, sync=False)
        sink.set_property("async", False)
        elements += [conv_enc, caps, encoder, parser, payloader, sink]
    else:
        elements += [make("fakesink", "fake-sink", sync=False)]

    for elem in elements:
        pipeline.add(elem)

    # Dynamic link: nvurisrcbin creates its pad once the stream is negotiated
    mux_sink = mux.request_pad_simple("sink_0") if hasattr(mux, "request_pad_simple") \
        else mux.get_request_pad("sink_0")
    source.connect("pad-added", on_source_pad, mux_sink)

    # Static links: mux -> ... -> sink
    chain = elements[1:]
    for upstream, downstream in zip(chain, chain[1:]):
        if not upstream.link(downstream):
            sys.exit(f"Failed to link {upstream.get_name()} -> {downstream.get_name()}")

    # Probe after nvdsanalytics: detection + tracking + colour + crossing meta are all ready here
    analytics.get_static_pad("src").add_probe(Gst.PadProbeType.BUFFER, counter.probe, None)
    return pipeline


def bus_call(_bus, message, loop):
    t = message.type
    if t == Gst.MessageType.EOS:
        log.info("End of stream")
        loop.quit()
    elif t == Gst.MessageType.WARNING:
        err, dbg = message.parse_warning()
        log.warning("%s: %s", err, dbg)
    elif t == Gst.MessageType.ERROR:
        err, dbg = message.parse_error()
        log.error("%s: %s", err, dbg)
        loop.quit()
    return True


def parse_line(text):
    vals = [float(v) for v in text.split(",")]
    if len(vals) != 4:
        raise argparse.ArgumentTypeError("--line needs 4 numbers: x1,y1,x2,y2")
    return vals


def main():
    ap = argparse.ArgumentParser(description="DeepStream vehicle detection, colour, tracking and counting")
    ap.add_argument("--uri", default="rtsp://127.0.0.1:8554/traffic", help="input RTSP URI")
    ap.add_argument("--db-url", default=os.getenv("DATABASE_URL",
                    "postgresql://vehicle:vehicle@127.0.0.1:5432/vehicle_analytics"))
    ap.add_argument("--line", type=parse_line, default=[0, 430, MUX_W, 430],
                    help=f"counting line x1,y1,x2,y2 in {MUX_W}x{MUX_H} pixels")
    ap.add_argument("--sink", choices=["rtsp", "fake"], default="rtsp",
                    help="rtsp = publish annotated video, fake = headless")
    ap.add_argument("--encoder", choices=["nvenc", "x264"], default="nvenc")
    ap.add_argument("--skip-color", action="store_true",
                    help="run without the colour classifier (debug only)")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s")

    if not os.path.isfile(os.path.join(CFG, "pgie_trafficcamnet.txt")):
        sys.exit("Missing configs/pgie_trafficcamnet.txt - run: python3 scripts/prepare_pgie_config.py")
    if not args.skip_color and not os.path.isfile(
            os.path.join(HERE, "..", "models", "color", "vehicle_color_resnet18.onnx")):
        sys.exit("Missing colour model - see color_classifier/README.md (or use --skip-color)")

    Gst.init(None)

    writer = DBWriter(args.db_url)
    writer.start()
    counter = VehicleCounter(writer)

    pipeline = build_pipeline(args, counter)
    server = start_rtsp_server() if args.sink == "rtsp" else None  # noqa: F841 (keep reference)

    loop = GLib.MainLoop()
    bus = pipeline.get_bus()
    bus.add_signal_watch()
    bus.connect("message", bus_call, loop)
    signal.signal(signal.SIGINT, lambda *_: loop.quit())
    signal.signal(signal.SIGTERM, lambda *_: loop.quit())

    log.info("Starting pipeline: %s", args.uri)
    pipeline.set_state(Gst.State.PLAYING)
    try:
        loop.run()
    finally:
        log.info("Stopping...")
        pipeline.set_state(Gst.State.NULL)
        writer.stop()


if __name__ == "__main__":
    main()
