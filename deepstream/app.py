#!/usr/bin/env python3
"""
Real-time vehicle analytics pipeline  (NVIDIA DeepStream 7.1, Python / pyds)

    RTSP (MediaMTX)
      -> nvurisrcbin        decode on GPU (NVDEC), auto-reconnect
      -> nvstreammux        batch frames (1 camera today, N cameras later)
      -> nvinfer  (PGIE)    TrafficCamNet: detect vehicles
      -> nvtracker          NvDCF: give each vehicle a stable ID
      -> nvinfer  (SGIE)    ResNet18: classify colour of each vehicle crop
      -> nvdsanalytics      line-crossing check (direction-aware)
      -> [probe]            read metadata -> count -> queue event -> PostgreSQL
      -> nvdsosd            draw boxes, IDs, colours, line, counters
      -> H.264 encoder -> RTSP server :8555/ds  (MediaMTX re-publishes it as
                                                 /processed over RTSP + HLS)

Usage:
    python3 app.py --uri rtsp://127.0.0.1:8554/traffic \
                   --db-url postgresql://vehicle:vehicle@127.0.0.1:5432/vehicle_analytics
"""
