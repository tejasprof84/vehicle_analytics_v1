HERE = os.path.dirname(os.path.abspath(__file__))
CFG = os.path.join(HERE, "configs")

PGIE_ID = 1          # gie-unique-id of the vehicle detector
SGIE_ID = 2          # gie-unique-id of the colour classifier
MUX_W, MUX_H = 1280, 720
RTSP_OUT_PORT = 8555
RTSP_OUT_MOUNT = "/ds"
UDP_PORT = 5400      # internal hop: encoder -> udpsink -> RTSP server

log = logging.getLogger("pipeline")


# ---------------------------------------------------------------------------
# nvdsanalytics config (generated from the --line argument)
# ---------------------------------------------------------------------------
def write_analytics_config(line, path):
    """
    nvdsanalytics line-crossing entries have 8 numbers:
        dx1;dy1;dx2;dy2 ; lx1;ly1;lx2;ly2
        \\_ direction _/   \\____ line ____/
    A crossing is reported only when the object moves in the direction of the
    arrow. We create two entries on the SAME line with opposite arrows, so we
    know if a vehicle went "in" or "out".
    """
    x1, y1, x2, y2 = line
    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
    length = math.hypot(x2 - x1, y2 - y1) or 1.0
    nx, ny = -(y2 - y1) / length * 80, (x2 - x1) / length * 80  # normal, 80 px long

    def entry(sx, sy, ex, ey):
        pts = [sx, sy, ex, ey, x1, y1, x2, y2]
        return ";".join(str(int(round(p))) for p in pts)

    text = f"""# AUTO-GENERATED by app.py from --line {x1},{y1},{x2},{y2}
# Coordinates are in nvstreammux resolution ({MUX_W}x{MUX_H}).
[property]
enable=1
config-width={MUX_W}
config-height={MUX_H}
# 2 = draw lines + object analytics info on the video
osd-mode=2
display-font-size=14

[line-crossing-stream-0]
enable=1
# format: direction(x1;y1;x2;y2) ; line(x1;y1;x2;y2)
line-crossing-in={entry(mx - nx, my - ny, mx + nx, my + ny)}
line-crossing-out={entry(mx + nx, my + ny, mx - nx, my - ny)}
# -1 = all classes (only vehicles reach this point anyway)
class-id=-1
extended=0
# balanced = good trade-off between missed and false crossings
mode=balanced
"""
    with open(path, "w") as f:
        f.write(text)
    return path


