#!/usr/bin/env python3
"""
Generate deepstream/configs/pgie_trafficcamnet.txt from the TrafficCamNet
config that ships with DeepStream.

Why generate instead of hard-coding?
  Model file names change between DeepStream releases (e.g. .etlt -> .onnx).
  Starting from the SDK's own config keeps the model, calibration file and
  tensor names correct for the installed version. We only:
    * turn relative model paths into absolute paths,
    * set batch-size=1 (one camera),
    * keep only the 'car' class (TrafficCamNet also detects bicycle/person/roadsign),
    * name the cached TensorRT engine so it is reused on the next run.
"""
import configparser
import os
import sys

DS_ROOT = "/opt/nvidia/deepstream/deepstream"
SAMPLE_CFG = os.path.join(DS_ROOT, "samples/configs/deepstream-app/config_infer_primary.txt")
OUT_CFG = os.path.join(os.path.dirname(__file__), "..", "deepstream", "configs", "pgie_trafficcamnet.txt")

PATH_KEYS = ("onnx-file", "model-file", "proto-file", "tlt-encoded-model",
             "int8-calib-file", "labelfile-path", "model-engine-file")
MODE_NAME = {"0": "fp32", "1": "int8", "2": "fp16"}


def main() -> None:
    if not os.path.isfile(SAMPLE_CFG):
        sys.exit(f"Sample config not found: {SAMPLE_CFG} (is DeepStream installed?)")

    cfg = configparser.ConfigParser(interpolation=None)
    cfg.optionxform = str  # keep key case as-is
    cfg.read(SAMPLE_CFG)
    prop = cfg["property"]
    base = os.path.dirname(SAMPLE_CFG)

    # 1) relative -> absolute paths
    for key in PATH_KEYS:
        if key in prop and not os.path.isabs(prop[key]):
            prop[key] = os.path.normpath(os.path.join(base, prop[key]))

    # 2) single stream
    prop["batch-size"] = "1"
    prop["gie-unique-id"] = "1"
    prop["process-mode"] = "1"  # primary (full frame)

    # INT8 needs a calibration file; fall back to FP16 if it is missing
    if prop.get("network-mode") == "1" and not os.path.isfile(prop.get("int8-calib-file", "")):
        prop["network-mode"] = "2"

    # 3) keep only vehicles ("car" class of TrafficCamNet)
    labels_path = prop["labelfile-path"]
    with open(labels_path) as f:
        labels = [l.strip() for l in f.read().replace(";", "\n").splitlines() if l.strip()]
    keep = {i for i, name in enumerate(labels) if name.lower() == "car"}
    drop = [str(i) for i in range(len(labels)) if i not in keep]
    if drop:
        prop["filter-out-class-ids"] = ";".join(drop)

    # 4) cache the TensorRT engine next to the model (built once, reused later)
    model = prop.get("onnx-file") or prop.get("tlt-encoded-model") or prop.get("model-file")
    mode = MODE_NAME.get(prop.get("network-mode", "2"), "fp16")
    prop["model-engine-file"] = f"{model}_b1_gpu0_{mode}.engine"

    os.makedirs(os.path.dirname(OUT_CFG), exist_ok=True)
    with open(OUT_CFG, "w") as f:
        f.write("# AUTO-GENERATED by scripts/prepare_pgie_config.py from the DeepStream sample\n")
        f.write("# Primary detector: TrafficCamNet (ResNet18 DetectNet_v2), vehicles only\n")
        cfg.write(f)

    print(f"Wrote {os.path.normpath(OUT_CFG)}")
    print(f"  labels: {labels}  -> kept {sorted(keep)}  (filtered {drop})")
    print(f"  model : {model}  mode: {mode}")


if __name__ == "__main__":
    main()
